def generate_dataset():
    rows = []
    for intent, examples in INTENT_DATA.items():
        for ex in examples:
            rows.append({"text": ex.strip(), "intent": intent})

    df = pd.DataFrame(rows)
    print(f"Total samples: {len(df)}")
    print(f"Total intents: {df['intent'].nunique()}")
    print("\nClass distribution:")
    print(df['intent'].value_counts())

    # Save complete dataset
    csv_path = os.path.join(os.path.dirname(__file__), "data", "intents.csv")
    df.to_csv(csv_path, index=False)
    print(f"\nSaved full dataset to {csv_path}")

    # Create stratified train/val/test splits (70% train, 15% val, 15% test)
    train_df, test_val_df = train_test_split(df, test_size=0.30, random_state=42, stratify=df["intent"])
    val_df, test_df = train_test_split(test_val_df, test_size=0.50, random_state=42, stratify=test_val_df["intent"])

    train_path = os.path.join(os.path.dirname(__file__), "data", "train.csv")
    val_path = os.path.join(os.path.dirname(__file__), "data", "val.csv")
    test_path = os.path.join(os.path.dirname(__file__), "data", "test.csv")

    train_df.to_csv(train_path, index=False)
    val_df.to_csv(val_path, index=False)
    test_df.to_csv(test_path, index=False)

    print(f"Train split: {len(train_df)} samples -> {train_path}")
    print(f"Val split:   {len(val_df)} samples -> {val_path}")
    print(f"Test split:  {len(test_df)} samples -> {test_path}")

if __name__ == "__main__":
    generate_dataset()
